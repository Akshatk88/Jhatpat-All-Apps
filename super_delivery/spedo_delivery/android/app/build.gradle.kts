        }
    }

    buildTypes {
        release {
            // Signed with android/key.properties when present (never committed);
            // a checkout without it still builds, falling back to the debug key.
            signingConfig = if (keystorePropertiesFile.exists()) {
                signingConfigs.getByName("release")
            } else {
                signingConfigs.getByName("debug")
            }
        }
    }
}

